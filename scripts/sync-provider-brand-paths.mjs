/**
 * Sync monochrome brand SVG paths from @lobehub/icons Mono components.
 * Fetches source files from the npm registry (no local @lobehub/icons install).
 * Run: pnpm sync:provider-icons
 */
import { writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const LOBEHUB_ICONS_VERSION = '5.14.0'
const ICONS_CDN_BASE = `https://unpkg.com/@lobehub/icons@${LOBEHUB_ICONS_VERSION}/es`

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')

const BRANDS = [
  ['anthropic', 'Anthropic'],
  ['arcee', 'Arcee'],
  ['cohere', 'Cohere'],
  ['deepseek', 'DeepSeek'],
  ['gemini', 'Gemini'],
  ['google', 'Google'],
  ['groq', 'Groq'],
  ['meta', 'Meta'],
  ['microsoft', 'Microsoft'],
  ['mistral', 'Mistral'],
  ['nvidia', 'Nvidia'],
  ['ollama', 'Ollama'],
  ['openai', 'OpenAI'],
  ['openrouter', 'OpenRouter'],
  ['perplexity', 'Perplexity'],
  ['qwen', 'Qwen'],
  ['xai', 'XAI']
]

function extractPaths(source) {
  const paths = [...source.matchAll(/d:\s*"([^"]+)"/g)].map((match) => match[1])
  if (!paths.length) throw new Error('No SVG paths found in Mono component')
  return paths.length === 1 ? paths[0] : paths
}

async function fetchMono(folder) {
  const url = `${ICONS_CDN_BASE}/${folder}/components/Mono.js`
  const response = await fetch(url)
  if (!response.ok) {
    throw new Error(`Failed to fetch ${url}: ${response.status} ${response.statusText}`)
  }
  return response.text()
}

const paths = {}
for (const [slug, folder] of BRANDS) {
  const source = await fetchMono(folder)
  paths[slug] = extractPaths(source)
}

const out = `// Generated by scripts/sync-provider-brand-paths.mjs — do not edit by hand.
export const PROVIDER_BRAND_PATHS = ${JSON.stringify(paths, null, 2)} as const

export type ProviderBrandSlug = keyof typeof PROVIDER_BRAND_PATHS

export const PROVIDER_BRAND_ALIASES: Record<string, ProviderBrandSlug> = {
  'meta-llama': 'meta',
  'x-ai': 'xai'
}

export function resolveProviderBrandSlug(key: string): ProviderBrandSlug | undefined {
  const normalized = key.toLowerCase()
  if (normalized in PROVIDER_BRAND_PATHS) return normalized as ProviderBrandSlug
  return PROVIDER_BRAND_ALIASES[normalized]
}
`

writeFileSync(
  join(
    root,
    'src',
    'renderer',
    'src',
    'features',
    'chat',
    'components',
    'composer',
    'providerBrandPaths.ts'
  ),
  out,
  'utf8'
)

console.log(`Wrote ${BRANDS.length} brand paths from @lobehub/icons@${LOBEHUB_ICONS_VERSION}`)
